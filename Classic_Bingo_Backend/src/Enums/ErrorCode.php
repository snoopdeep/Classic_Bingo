 * The string value of each case maps directly to a code in errors.json.
 */
enum ErrorCode: string
{
    // === Infrastructure & Routing Errors (00) ===
    case INFRA_UNEXPECTED_ERROR = 'ERR_00_INFRA_UNEXPECTED';
    case INFRA_DATABASE_ERROR = 'ERR_00_INFRA_DATABASE';
    case ROUTING_NOT_FOUND = 'ERR_00_ROUTING_NOT_FOUND';
    case INFRA_CACHE_CONNECTION_FAILED = 'ERR_00_INFRA_CACHE_CONNECTION';


    // === Authentication & Authorization Errors (01) ===
    case AUTH_ACCESS_TOKEN_MISSING = 'ERR_01_AUTH_ACCESS_TOKEN_MISSING';
    case AUTH_ACCESS_TOKEN_EXPIRED = 'ERR_01_AUTH_ACCESS_TOKEN_EXPIRED'; 
    case AUTH_ACCESS_TOKEN_INVALID = 'ERR_01_AUTH_ACCESS_TOKEN_INVALID';
    case AUTH_REFRESH_TOKEN_MISSING = 'ERR_01_AUTH_REFRESH_TOKEN_MISSING';
    case AUTH_REFRESH_TOKEN_INVALID_OR_REVOKED = 'ERR_01_AUTH_REFRESH_TOKEN_INVALID';
    case AUTH_FORBIDDEN = 'ERR_01_AUTH_FORBIDDEN';
    case AUTH_USERNAME_TAKEN = 'ERR_01_AUTH_USERNAME_TAKEN';
    case AUTH_UNAUTHORIZED = 'ERR_01_AUTH_UNAUTHORIZED';
    case AUTH_MISSING_SIGNATURE = 'ERR_01_AUTH_MISSING_SIGNATURE';
    case AUTH_INVALID_SIGNATURE = 'ERR_01_AUTH_INVALID_SIGNATURE';
    case AUTH_INVALID_CREDENTIALS = 'ERR_01_AUTH_INVALID_CREDENTIALS';

