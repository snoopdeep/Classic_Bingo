    case VALIDATION_GAME_MODE_UNSUPPORTED = 'ERR_02_GAME_MODE_UNSUPPORTED';

    // === Resource Errors (03) ===
    case RESOURCE_USER_NOT_FOUND = 'ERR_03_RESOURCE_USER_NOT_FOUND';
    
    // === Game Logic Errors (04) ===
    case GAME_INVALID_BINGO_CALL = 'ERR_04_GAME_INVALID_BINGO_CALL';
    case GAME_NO_BINGO = 'ERR_04_GAME_NO_BINGO';
    case GAME_SESSION_NOT_FOUND = 'ERR_04_GAME_SESSION_NOT_FOUND';
    case GAME_INSUFFICIENT_FUNDS = 'ERR_04_GAME_INSUFFICIENT_FUNDS';

    case GAME_INVALID_REQUEST = 'ERR_04_GAME_INVALID_REQUEST';

    case GAME_MODE_UNSUPPORTED = 'ERR_04_GAME_MODE_UNSUPPORTED';
}